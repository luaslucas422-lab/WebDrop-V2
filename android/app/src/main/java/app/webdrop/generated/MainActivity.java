/** Full-screen WebView wrapper generated by WebDrop. No third-party dependencies. */
public class MainActivity extends Activity {
    private static final int FILE_REQ = 1;
    private static final String DESKTOP_UA =
            "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
                    + "Chrome/124.0.0.0 Safari/537.36";

    private WebView web;
    private ProgressBar bar;
    private ValueCallback<Uri[]> fileCallback;
    private long lastBack = 0;
    private boolean pageReady = false;
    private String pendingLink;

    private static final String CRASH = "webdrop-crash";

    @Override
    protected void onCreate(Bundle state) {
        super.onCreate(state);
        // Remember any crash so the next launch can show it instead of closing silently.
        final Thread.UncaughtExceptionHandler prev = Thread.getDefaultUncaughtExceptionHandler();
        Thread.setDefaultUncaughtExceptionHandler((t, e) -> {
            try {
                getSharedPreferences(CRASH, MODE_PRIVATE).edit().putString("trace", trace(e)).commit();
            } catch (Throwable ignored) {
            }
            if (prev != null) {
                prev.uncaughtException(t, e);
            }
        });
        String last = getSharedPreferences(CRASH, MODE_PRIVATE).getString("trace", null);
        if (last != null) {
            getSharedPreferences(CRASH, MODE_PRIVATE).edit().remove("trace").commit();
            showError("WebDrop closed unexpectedly last time.", last);
            return;
        }
        try {
            setUp(state);
        } catch (Throwable e) {
            showError("WebDrop couldn't start.", trace(e));
        }
    }

    private static String trace(Throwable e) {
        StringWriter w = new StringWriter();
        e.printStackTrace(new PrintWriter(w));
        String s = w.toString();
        return s.length() > 6000 ? s.substring(0, 6000) : s;
    }

    /** Plain error screen: take a screenshot and send it to the developer. */
    private void showError(String title, String details) {
        int pad = (int) (18 * getResources().getDisplayMetrics().density);
        LinearLayout box = new LinearLayout(this);
        box.setOrientation(LinearLayout.VERTICAL);
        box.setPadding(pad, pad * 2, pad, pad);
        box.setBackgroundColor(Color.parseColor("#10141c"));
        TextView h = new TextView(this);
        h.setText(title + "\nPlease screenshot this and send it to the developer.");
        h.setTextColor(Color.WHITE);
        h.setTextSize(17);
        box.addView(h);
        TextView v = new TextView(this);
        v.setText("Android " + Build.VERSION.RELEASE + " (API " + Build.VERSION.SDK_INT + "), " + Build.MANUFACTURER + " " + Build.MODEL
                + ", app " + BuildConfig.VERSION_NAME + "\n\n" + details);
        v.setTextColor(Color.parseColor("#ffb4b4"));
        v.setTextSize(12);
        v.setTextIsSelectable(true);
        v.setPadding(0, pad, 0, pad);
        box.addView(v);
        android.widget.Button again = new android.widget.Button(this);
        again.setText("Try again");
        again.setOnClickListener(x -> recreate());
        box.addView(again);
        ScrollView sv = new ScrollView(this);
        sv.addView(box);
        setContentView(sv);
    }

    @SuppressLint("SetJavaScriptEnabled")
    private void setUp(Bundle state) {
        if (BuildConfig.KEEP_SCREEN_ON) {
            getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        }

        FrameLayout root = new FrameLayout(this);
        web = new WebView(this);
        root.addView(web, new FrameLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));

        bar = new ProgressBar(this, null, android.R.attr.progressBarStyleHorizontal);
        bar.setMax(100);
        bar.setVisibility(View.GONE);
        int h = (int) (3 * getResources().getDisplayMetrics().density);
        root.addView(bar, new FrameLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, h, Gravity.TOP));
        setContentView(root);
        try {
            applyBarColors();
        } catch (Throwable ignored) {
            // cosmetic only
        }

        WebSettings s = web.getSettings();
        s.setJavaScriptEnabled(true);
        s.setDomStorageEnabled(true);
        // Only the app's own bundled pages (file:///android_asset/...) may use file access.
        s.setAllowFileAccess(BuildConfig.APP_URL.startsWith("file:///android_asset/"));
        s.setAllowContentAccess(false);
        s.setMixedContentMode(WebSettings.MIXED_CONTENT_NEVER_ALLOW);
        s.setSupportMultipleWindows(false);
        s.setSupportZoom(BuildConfig.ALLOW_ZOOM);
        s.setBuiltInZoomControls(BuildConfig.ALLOW_ZOOM);
        s.setDisplayZoomControls(false);
        if (BuildConfig.DESKTOP_MODE) {
            s.setUserAgentString(DESKTOP_UA);
            s.setUseWideViewPort(true);
            s.setLoadWithOverviewMode(true);
        }
        CookieManager.getInstance().setAcceptCookie(true);

        web.setWebViewClient(new WebViewClient() {
            @Override
            public boolean shouldOverrideUrlLoading(WebView view, WebResourceRequest request) {
                return shouldLeave(request.getUrl());
            }

            @Override
            public void onPageStarted(WebView view, String url, android.graphics.Bitmap favicon) {
                if (BuildConfig.SHOW_PROGRESS) {
                    bar.setVisibility(View.VISIBLE);
                }
            }

            @Override
            public void onPageFinished(WebView view, String url) {
                bar.setVisibility(View.GONE);
                pageReady = true;
                deliverLink();
            }

            @Override
            public void onReceivedError(WebView view, WebResourceRequest request, WebResourceError error) {
                if (request.isForMainFrame()) {
                    showOffline();
                }
            }
        });

        web.setWebChromeClient(new WebChromeClient() {
            @Override
            public void onProgressChanged(WebView view, int progress) {
                bar.setProgress(progress);
            }

            @Override
            public boolean onShowFileChooser(WebView view, ValueCallback<Uri[]> callback,
                                             FileChooserParams params) {
                if (fileCallback != null) {
                    fileCallback.onReceiveValue(null);
                }
                fileCallback = callback;
                try {
                    startActivityForResult(params.createIntent(), FILE_REQ);
                } catch (ActivityNotFoundException e) {
                    fileCallback = null;
                    return false;
                }
                return true;
            }
        });

        // Downloads are handed to the browser, which already knows how to save files.
        web.setDownloadListener((url, userAgent, contentDisposition, mimeType, length) ->
                openExternal(Uri.parse(url)));

        final Bundle saved = state;
        Runnable start = () -> {
            if (saved != null) {
                web.restoreState(saved);
            } else {
                web.loadUrl(BuildConfig.APP_URL);
            }
        };
        applyImmersive();
        if (BuildConfig.LOCK_HASH.isEmpty()) {
            start.run();
        } else {
            askPassword(start);
        }
        handleLink(getIntent());
    }

    /** App links like webdrop://auth?s=... (sign-in) or webdrop://licence?key=... (purchase) go to the page. */
    @Override
    protected void onNewIntent(Intent intent) {
        super.onNewIntent(intent);
        setIntent(intent);
        handleLink(intent);
    }

    private void handleLink(Intent intent) {
        if (intent == null || intent.getData() == null) {
            return;
        }
        Uri u = intent.getData();
        if (!BuildConfig.DEEP_SCHEME.equals(u.getScheme())) {
            return;
        }
        pendingLink = u.toString();
        deliverLink();
    }

    private void deliverLink() {
        if (pendingLink == null || !pageReady || web == null) {
            return;
        }
        String js = "window.WDDeep&&window.WDDeep(" + JSONObject.quote(pendingLink) + ")";
        pendingLink = null;
        web.evaluateJavascript(js, null);
    }

    /** Start password: the app only stores salt + SHA-256, never the password itself. */
    private void askPassword(Runnable onUnlock) {
        final EditText input = new EditText(this);
        input.setInputType(InputType.TYPE_CLASS_TEXT | InputType.TYPE_TEXT_VARIATION_PASSWORD);
        input.setFilters(new InputFilter[]{new InputFilter.LengthFilter(10)});
        input.setHint("Password");
        int pad = (int) (20 * getResources().getDisplayMetrics().density);
        FrameLayout box = new FrameLayout(this);
        box.setPadding(pad, pad / 2, pad, 0);
        box.addView(input);
        final AlertDialog dialog = new AlertDialog.Builder(this)
                .setTitle("Enter password")
                .setView(box)
                .setCancelable(false)
                .setPositiveButton("Unlock", null)
                .setNegativeButton("Exit", (d, w) -> finish())
                .create();
        dialog.setOnShowListener(d -> dialog.getButton(AlertDialog.BUTTON_POSITIVE).setOnClickListener(v -> {
            if (sha256(BuildConfig.LOCK_SALT + ":" + input.getText().toString()).equals(BuildConfig.LOCK_HASH)) {
                dialog.dismiss();
                onUnlock.run();
            } else {
                input.setText("");
                input.setError("Wrong password");
            }
        }));
        dialog.show();
    }

    private static String sha256(String s) {
        try {
            byte[] d = MessageDigest.getInstance("SHA-256").digest(s.getBytes(StandardCharsets.UTF_8));
            StringBuilder b = new StringBuilder();
            for (byte x : d) {
                b.append(String.format("%02x", x & 0xff));
            }
            return b.toString();
        } catch (Exception e) {
            return "";
        }
    }

    /** Returns true when the app should NOT load the URL itself. */
    private boolean shouldLeave(Uri uri) {
        String scheme = uri.getScheme();
        if (scheme == null) {
            return false;
        }
        if (scheme.equals("file")) {
            // bundled pages stay in the app; any other file: URL is blocked
            return !uri.toString().startsWith("file:///android_asset/");
        }
        if (scheme.equals("https") || scheme.equals("http")) {
            if (BuildConfig.INTERNAL_LINKS || sameSite(uri)) {
                return false;
            }
            openExternal(uri);
            return true;
        }
        if (scheme.equals("about") || scheme.equals("data") || scheme.equals("blob")) {
            return false;
        }
        if (scheme.equals(BuildConfig.DEEP_SCHEME)) {
            pendingLink = uri.toString();
            deliverLink();
            return true;
        }
        openExternal(uri); // tel:, mailto:, market:, ...
        return true;
    }

    private boolean sameSite(Uri uri) {
        String home = Uri.parse(BuildConfig.APP_URL).getHost();
        String host = uri.getHost();
        if (home == null || host == null) {
            return false;
        }
        return host.equals(home) || host.endsWith("." + home) || home.endsWith("." + host);
    }

    private void openExternal(Uri uri) {
        try {
            startActivity(new Intent(Intent.ACTION_VIEW, uri));
        } catch (ActivityNotFoundException ignored) {
            // nothing can open it; stay put
        }
    }

    private void showOffline() {
        String html = "<html><head><meta name='viewport' content='width=device-width,initial-scale=1'>"
                + "<style>body{font-family:sans-serif;background:#10141c;color:#e8eefc;display:flex;"
                + "align-items:center;justify-content:center;height:100vh;margin:0;text-align:center}"
                + "a{display:inline-block;margin-top:18px;padding:12px 22px;border-radius:12px;"
                + "background:#477fe0;color:#fff;text-decoration:none;font-weight:600}</style></head>"
                + "<body><div><h2>You're offline</h2><p>Check your connection and try again.</p>"
                + "<a href='" + BuildConfig.APP_URL + "'>Try again</a></div></body></html>";
        web.loadDataWithBaseURL(null, html, "text/html", "utf-8", null);
    }

    /** Optional custom status/navigation bar colour, with matching icon contrast. */
    @SuppressWarnings("deprecation")
    private void applyBarColors() {
        String hex = BuildConfig.STATUS_COLOR;
        if (hex == null || hex.isEmpty() || BuildConfig.IMMERSIVE) {
            return;
        }
        int color;
        try {
            color = Color.parseColor(hex);
        } catch (IllegalArgumentException e) {
            return;
        }
        Window w = getWindow();
        w.setStatusBarColor(color);
        w.setNavigationBarColor(color);
        boolean light = (0.299 * Color.red(color) + 0.587 * Color.green(color)
                + 0.114 * Color.blue(color)) > 160;
        if (Build.VERSION.SDK_INT >= 30) {
            WindowInsetsController c = w.getInsetsController();
            if (c != null) {
                int mask = WindowInsetsController.APPEARANCE_LIGHT_STATUS_BARS
                        | WindowInsetsController.APPEARANCE_LIGHT_NAVIGATION_BARS;
                c.setSystemBarsAppearance(light ? mask : 0, mask);
            }
        } else if (Build.VERSION.SDK_INT >= 23) {
            View d = w.getDecorView();
            int f = d.getSystemUiVisibility();
            d.setSystemUiVisibility(light
                    ? (f | View.SYSTEM_UI_FLAG_LIGHT_STATUS_BAR)
                    : (f & ~View.SYSTEM_UI_FLAG_LIGHT_STATUS_BAR));
        }
    }

    @SuppressWarnings("deprecation")
    private void applyImmersive() {
        if (!BuildConfig.IMMERSIVE) {
            return;
        }
        if (Build.VERSION.SDK_INT >= 28) {
            WindowManager.LayoutParams lp = getWindow().getAttributes();
            lp.layoutInDisplayCutoutMode = WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_SHORT_EDGES;
            getWindow().setAttributes(lp);
        }
        if (Build.VERSION.SDK_INT >= 30) {
            getWindow().setDecorFitsSystemWindows(false);
            WindowInsetsController c = getWindow().getInsetsController();
            if (c != null) {
                c.hide(WindowInsets.Type.systemBars());
                c.setSystemBarsBehavior(WindowInsetsController.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
            }
        } else {
            getWindow().getDecorView().setSystemUiVisibility(
                    View.SYSTEM_UI_FLAG_LAYOUT_STABLE
                            | View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION
                            | View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN
                            | View.SYSTEM_UI_FLAG_HIDE_NAVIGATION
                            | View.SYSTEM_UI_FLAG_FULLSCREEN
                            | View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY);
        }
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) {
            applyImmersive();
        }
    }

    @Override
    @SuppressWarnings("deprecation")
    protected void onActivityResult(int requestCode, int resultCode, Intent data) {
        if (requestCode == FILE_REQ && fileCallback != null) {
            fileCallback.onReceiveValue(WebChromeClient.FileChooserParams.parseResult(resultCode, data));
            fileCallback = null;
            return;
        }
        super.onActivityResult(requestCode, resultCode, data);
    }

    @Override
    @SuppressWarnings("deprecation")
    public void onBackPressed() {
        if (web != null && web.canGoBack()) {
            web.goBack();
            return;
        }
        if (BuildConfig.CONFIRM_EXIT) {
            long now = System.currentTimeMillis();
            if (now - lastBack > 2000) {
                lastBack = now;
                Toast.makeText(this, "Press back again to exit", Toast.LENGTH_SHORT).show();
                return;
            }
        }
        super.onBackPressed();
    }

    @Override
    protected void onSaveInstanceState(Bundle out) {
        super.onSaveInstanceState(out);
        if (web != null) {
            web.saveState(out);
        }
    }

    @Override
    protected void onPause() {
        if (web != null) {
            web.onPause();
        }
        super.onPause();
    }

    @Override
    protected void onResume() {
        super.onResume();
        if (web != null) {
            web.onResume();
        }
    }

    @Override
    protected void onDestroy() {
        if (web != null) {
            web.destroy();
        }
        super.onDestroy();
    }
}
