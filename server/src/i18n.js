export function pickLang(v) {
  const l = String(v || '').slice(0, 2).toLowerCase();
  return LANGS.includes(l) ? l : 'en';
}

// Server-side: translate a string for a page.
export function tr(lang, s, x) {
  const d = T[lang] || {};
  const out = d[s] || s;
  return x === undefined ? out : out.split('{x}').join(x);
}

// Client-side helper injected into each page: window.L(s, x) and money formatting.
export function clientI18n(lang) {
  return `<script>window.WL=${JSON.stringify(lang)};window.WT=${JSON.stringify(T[lang] || {}).replace(/</g, '\\u003c')};window.L=(s,x)=>{const o=WT[s]||s;return x===undefined?o:o.split('{x}').join(x)};window.EUR=c=>{try{return new Intl.NumberFormat(WL,{style:'currency',currency:'EUR',minimumFractionDigits:c%100?2:0}).format(c/100)}catch(e){return '€'+(c%100?(c/100).toFixed(2):String(c/100))}};</script>`;
}
